const fs = require('fs');
const path = require('path');

// Configuration
const SOURCE_DIR = 'C:\\Users\\daniu\\Local Sites\\kids-over-profits\\app\\public\\wp-content\\themes\\child\\markdown_output';
const SQL_OUTPUT_FILE = 'update_organizations.sql';

// Sections that indicate this file is an Organization listing other programs
const TARGET_SECTIONS = [
    'Programs',
    'Facilities',
    'Schools',
    'Locations',
    'Affiliated Programs',
    'Affiliated Companies',
    'WWASP Programs',
    'WWASP-Affiliated',
    'Owned Programs',
    'Closed Programs',
    'Active Programs',
    'Residential Programs'
];

async function generateOrganizationSQL() {
    console.log('Starting SQL Generation for Facility Organization...');
    console.log(`Source Dir: ${SOURCE_DIR}`);
    console.log(`SQL Output: ${SQL_OUTPUT_FILE}`);
    console.log('------------------------------------------------');

    if (!fs.existsSync(SOURCE_DIR)) {
        console.error(`Error: Directory not found.`);
        return;
    }

    const files = fs.readdirSync(SOURCE_DIR).filter(f => f.endsWith('.md'));
    let totalUpdates = 0;
    const sqlStatements = [];

    // Add a header to the SQL file
    sqlStatements.push('-- SQL statements to backfill organization column based on markdown files');
    sqlStatements.push('-- Generated by organize-facilities.js script');
    sqlStatements.push('-- Run these statements against your WordPress database.');
    sqlStatements.push('');

    // Pre-fetch all entries to build a lookup map of program_name to id, and current organization
    // Since API is broken, this requires direct DB interaction or a pre-exported JSON.
    // For now, we will *assume* the target programs exist and output the SQL.
    // The previous scan script verified we can identify children names.
    // However, to make this truly robust without the API, we need a way to get all program names and their IDs.
    // For this demonstration, I will assume a programmatic lookup that would happen against the DB.
    // Since I cannot access the DB directly, the generated SQL will rely on program_name.
    // It is CRUCIAL that program_name in the DB is unique or this will update multiple rows.

    console.warn('WARNING: This script will generate SQL statements that update the `organization` column based on `program_name`.');
    console.warn('         Ensure `program_name` is unique in your `wiki_submissions` table or adjust SQL manually.');
    console.warn('         You will need to manually execute the generated SQL file.');
    console.log('------------------------------------------------');


    for (const file of files) {
        const filePath = path.join(SOURCE_DIR, file);
        const content = fs.readFileSync(filePath, 'utf8');

        // 1. Determine Organization Name (Parent)
        let parentName = '';
        const headerMatch = content.match(/^#{1,3}\s*\*{0,2}(.+?)\*{0,2}\s*(\(|$)/m);
        if (headerMatch) {
            parentName = headerMatch[1].trim();
        } else {
            parentName = path.parse(file).name;
        }

        if (!parentName || parentName.includes('Page title')) continue;

        // 2. Scan for Target Sections and Extract Links
        let foundChildrenNames = []; // Just names for now
        
        const extractLinks = (text) => {
            const links = [];
            const linkRegex = /\[([^\]]+)\]\(([^)]+)\)/g;
            let match;
            while ((match = linkRegex.exec(text)) !== null) {
                const name = match[1].replace(/\*\*/g, '').trim();
                const url = match[2].trim();
                
                const isWiki = url.includes('/wiki/') || url.includes('/r/troubledteens/');
                const isUser = url.includes('/u/') || url.includes('/user/');
                const isIndex = url.endsWith('/index') || url.endsWith('/index/');
                
                if (isWiki && !isUser && !isIndex && name.toLowerCase() !== parentName.toLowerCase()) {
                    links.push(name);
                }
            }
            return links;
        };

        const sections = content.split(/^##\s+/gm);
        let isOrganizationFile = false;

        for (const section of sections) {
            const firstLineEnd = section.indexOf('\n');
            if (firstLineEnd === -1) continue;
            
            const titleLine = section.substring(0, firstLineEnd).trim();
            const cleanTitle = titleLine.replace(/[\*_]/g, ''); 
            const body = section.substring(firstLineEnd);

            const isTargetSection = TARGET_SECTIONS.some(target => 
                cleanTitle.toLowerCase().includes(target.toLowerCase())
            );

            if (isTargetSection) {
                const links = extractLinks(body);
                if (links.length > 0) {
                    foundChildrenNames.push(...links);
                    isOrganizationFile = true;
                }
            }
        }

        if (isOrganizationFile && foundChildrenNames.length > 0) {
            console.log(`\n[ORGANIZATION] "${parentName}" (File: ${file})`);
            console.log(`  Found ${foundChildrenNames.length} programs. Generating SQL...`);

            // Generate SQL for each child
            foundChildrenNames.forEach(childName => {
                // Escape names for SQL
                const escapedChildName = childName.replace(/'/g, "''");
                const escapedParentName = parentName.replace(/'/g, "''");

                // Update statement - CRITICAL: Assumes program_name is unique!
                const sql = `UPDATE \`wiki_submissions\` SET \`organization\` = '${escapedParentName}' WHERE \`program_name\` = '${escapedChildName}' AND (\`organization\` IS NULL OR \`organization\` = '');`;
                sqlStatements.push(sql);
                totalUpdates++;
            });
        }
    }

    // Write all SQL statements to the output file
    fs.writeFileSync(SQL_OUTPUT_FILE, sqlStatements.join('\n') + '\n', 'utf8');

    console.log('------------------------------------------------');
    console.log(`SQL Generation Complete. Generated ${totalUpdates} UPDATE statements.`);
    console.log(`File created: ${SQL_OUTPUT_FILE}`);
    console.log('Please execute this SQL file against your database manually.');
}

generateOrganizationSQL().catch(err => console.error(err));